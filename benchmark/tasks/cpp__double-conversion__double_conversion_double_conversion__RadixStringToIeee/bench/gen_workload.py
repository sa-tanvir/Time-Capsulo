SIZES = {"S": (60, 24, 8, 3), "M": (400, 100, 300, 4), "L": (200, 220, 20000, 6)}   # n per line, nd, pad, lines


def lines(size, rng):
    n, nd, pad, nl = SIZES[size]
    out = []
    if size == "S":
        for rl, sg, sep, hf, junk0, dbl, wide, s in LIT:
            for junk in (0, 1):
                if hf and junk == 0 and s.endswith("zz"):
                    continue
                out.append("L\t1\t%d\t%d\t%d\t%d\t%d\t%d\t%d\t%s" % (rl, sg, sep, hf, junk, dbl, wide, s))
    for _ in range(nl):
        out.append("G\t1\t%d\t%d\t%d\t%d" % (rng.randrange(1, 2**62), n, nd, pad))
    return out


