"""Seeded workload generator for generic_jaro (strsim-rs). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <reps> <a> <b>                              literal pair
  G <reps> <seed> <len> <alpha> <pct> <mode>    pair generated by the driver (splitmix64):
      a = <len> random chars over the first <alpha> chars of a fixed 64-char alphabet (ASCII letters
      then multibyte chars), b = a with <pct>% of positions edited; mode "eq" = substitutions and
      adjacent swaps only (same length), "any" = also insertions/deletions.
<reps> = how many times the call is repeated on that pair in time mode.
"""
import random, sys
from pathlib import Path

LITERALS = [('', ''), ('', 'jaro'), ('distance', ''), ('jaro', 'jaro'), ('a', 'b'), ('a', 'a'), ('a', 'ab'), ('ab', 'a'), ('dixon', 'dicksonx'), ('dwayne', 'duane'), ('martha', 'marhta'), ('Friedrich Nietzsche', 'Jean-Paul Sartre'), ('testabctest', 'testöঙ香test'), ('kitten', 'sitting'), ('hello, world', 'bye, world'), ('öঙ香', 'abc'), ('abc', 'öঙ香'), ('ca', 'abc'), ('ac', 'cba'), ('ab', 'bca'), ('damerau', 'aderua'), ('aderua', 'damerau'), ('damerau', 'aderuaxyz'), ('aderuaxyz', 'damerau'), ('Stewart', 'Colbert'), ('abcdefghijkl', 'bacedfgihjlk'), ('foobar', 'ofobar'), ('specter', 'spectre'), ('a cat', 'an abct'), ('cheeseburger', 'cheese fries'), ('Dinsdale', 'D'), ('Thorkel', 'Thorgier'), ('The quick brown fox jumped over the angry dog.', 'Lehem ipsum dolor sit amet, dicta latine an eam.'), ('levenshtein', 'löwenbräu'), ('aaaa', 'aaa'), ('abab', 'baba')]

SIZES = {'S': (30, (1, 200), 1), 'M': (40, (300, 1000), 1), 'L': (60, (1000, 3000), 1)}   # size -> (n_generated_cases, (min_len, max_len), reps)


def lines(size, rng):
    n, (lo, hi), reps = SIZES[size]
    out = []
    if size == "S":
        out += ["L\t1\t%s\t%s" % (a, b) for a, b in LITERALS]
    for _ in range(n):
        mode = rng.choice(['any'])
        out.append("G\t%d\t%d\t%d\t%d\t%d\t%s" % (reps, rng.randrange(1, 2**62), rng.randint(lo, hi),
                                               rng.choice([2, 4, 26, 52, 64]), rng.choice([0, 1, 5, 20, 50]), mode))
    return out


if __name__ == "__main__":
    out_dir = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20190509 + i)
        (out_dir / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
