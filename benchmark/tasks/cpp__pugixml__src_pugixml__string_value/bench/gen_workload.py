"""Seeded workload generator for string_value (pugixml). Usage: python3 gen_workload.py <out_dir>

Tab-separated lines, parsed by driver.cpp:
  L <reps> <embed> <xml>                          literal document (escapes \\t \\n \\r \\\\ allowed)
  G <reps> <seed> <items> <maxdepth> <embed>      document generated by the driver (splitmix64): <items> items (elements with 0-2 attributes,
      text with entities, CDATA, comments, processing instructions, empty elements) nested up to <maxdepth> levels under <root>
<embed>: 1 = parse with parse_embed_pcdata (an element's first text child is stored as the element's own value), 0 = default
The driver parses each document with parse_default | parse_comments | parse_pi | parse_declaration | parse_doctype and asks for the string value
of the document node, a sample of its descendants (chosen by a size budget) and the first attributes of the sampled elements.
"""
import random, sys
from pathlib import Path

LITERALS = [
    "<a/>", "<a>text</a>", "<a>one<b>two</b>three<c><d>four</d></c>five</a>", "<a><!--comment--><?pi data?>x<![CDATA[<cd>&]]>y</a>",
    "<?xml version='1.0'?><!DOCTYPE d><d a='1' b='two &amp; three'><e>t</e></d>", "<a>x&lt;y&amp;z&#65;</a>", "<a> </a>",
    "<a><b/><b/><b/></a>", "<a>\\n  <b>\\n    text\\n  </b>\\n</a>", "<a><b><c><d><e><f>deep</f></e></d></c></b></a>", "<a><![CDATA[]]></a>", "<a>t1<b>t2</b>t3<!--c-->t4<?p i?>t5</a>",
    "<x:a xmlns:x='u' x:b='attr value'>q</x:a>",
]

SIZES = {'S': (8, (10, 60), 1), 'M': (8, (20000, 50000), 2), 'L': (8, (200000, 400000), 1)}   # size -> (n_G_cases, (min_items, max_items), reps)


def lines(size, rng):
    n, (lo, hi), reps = SIZES[size]
    out = []
    if size == "S":
        for s in LITERALS:
            for embed in (0, 1):
                out.append("L\t1\t%d\t%s" % (embed, s))
    for i in range(n):
        out.append("G\t%d\t%d\t%d\t%d\t%d" % (reps, rng.randrange(1, 2**62), rng.randint(lo, hi), rng.choice([3, 6, 12, 40]), i % 2))
    return out


if __name__ == "__main__":
    out_dir = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20190912 + i)
        (out_dir / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
