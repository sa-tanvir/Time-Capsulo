"""Seeded workload generator for decode_last_utf8 (regex 1.0.0). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <reps> <hex bytes>                  literal buffer (each literal is decoded once, as a whole)
  G <reps> <seed> <len> <bad_permille>  buffer of ~<len> bytes generated by the driver (splitmix64): a mix of
        1/2/3/4-byte UTF-8 characters, with <bad_permille>/1000 of the units replaced by invalid material
        (stray continuation bytes, truncated sequences, overlong forms, surrogates, 0xF8-0xFF, > U+10FFFF).
  For G buffers the driver walks the buffer backwards, calling decode_last_utf8 on ever shorter prefixes.
<reps> = how many times the case is repeated in time mode.
"""
import random, sys
from pathlib import Path

LITERALS = [b"", b"a", b"\x7f", b"\xff", b"\xed\xa0\x81", b"\xc3", b"\xef\xbf", b"\xf4\x8f\xbf",
            b"\xc0\xa1", b"\xe0\x80\xa1", b"\xf0\x80\x80\xa1", b"\xc3\xa9", b"\xe6\x97\xa5", b"\xf0\x9f\x98\x80",
            b"\xf4\x8f\xbf\xbf", b"\xf4\x90\x80\x80", b"x\xc3\xa9", b"\x80", b"\x80\x80\x80\x80", b"a\x80",
            b"\x80\x80\x80\x80\x80", b"\xc3\xa9\xa9", b"\xe6\x97\xa5\x80", b"ab\xf0\x9f\x98", b"\xf8\x88\x80\x80\x80",
            b"\xd4\xc2", b"\xc2\x80", b"\xdf\xbf", b"\xe0\xa0\x80", b"\xed\x9f\xbf", b"\xee\x80\x80", b"\xf0\x90\x80\x80",
            b"\xe0\xa0", b"zz\xe0\xa0\x80"]

SIZES = {"S": (20, (10, 100), 50), "M": (20, (2000, 6000), 5), "L": (20, (30000, 90000), 10)}


def lines(size, rng):
    n, (lo, hi), reps = SIZES[size]
    out = []
    if size == "S":
        out += ["L\t%d\t%s" % (reps * 10, b.hex()) for b in LITERALS]
    for _ in range(n):
        out.append("G\t%d\t%d\t%d\t%d" % (reps, rng.randrange(1, 2**62), rng.randint(lo, hi),
                                          rng.choice([0, 0, 5, 50, 300, 1000])))
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180502 + 400 + i)
        (out / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
