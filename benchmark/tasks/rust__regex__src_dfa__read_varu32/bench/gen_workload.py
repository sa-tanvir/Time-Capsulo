"""Seeded workload generator for read_varu32 (regex 1.0.0). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <reps> <hex bytes>                  literal buffer, decoded once (single call)
  G <reps> <seed> <count> <tail>        stream generated by the driver (splitmix64): <count> LEB128 varints
        (values of 1-5 byte magnitude, some padded with redundant 0x80 bytes up to 5 bytes total),
        followed, if <tail> = 1, by 1-4 continuation bytes with no terminator. The driver decodes the
        stream from the front, advancing by the returned length until it returns length 0.
<reps> = how many times the case is repeated in time mode.
"""
import random, sys
from pathlib import Path

LITERALS = ["", "00", "01", "7f", "8001", "ff01", "ac02", "e807", "808001", "ffff03", "ffffff7f", "ffffffff0f",
            "80", "ff", "8080", "ffffffff", "808080800f", "8000", "8080808000", "0a0b", "96010203", "7f80"]

SIZES = {"S": (20, (5, 50), 300), "M": (20, (500, 3000), 20), "L": (20, (20000, 60000), 10)}


def lines(size, rng):
    n, (lo, hi), reps = SIZES[size]
    out = []
    if size == "S":
        out += ["L\t%d\t%s" % (reps * 20, h) for h in LITERALS]
    for _ in range(n):
        out.append("G\t%d\t%d\t%d\t%d" % (reps, rng.randrange(1, 2**62), rng.randint(lo, hi), rng.choice([0, 0, 1])))
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180502 + 800 + i)
        (out / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
