"""Seeded workload generator for Help::write_templated_help (clap). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <app> <template>              literal template (\\n = newline, \\t = tab, \\\\ = backslash)
  G <app> <n_segments> <seed>     template generated by the driver (xorshift seeded with <seed>): <n_segments>
                                  pieces, each a run of plain text or one tag / malformed-brace construct
<app>: 0 = app with every meta field set (name, version, author, about, long about, before/after help, args,
subcommands), 1 = bare app "bare" (no meta), 2 = subcommand-style app whose bin_name contains a space.
"""
import random, sys
from pathlib import Path

LITERALS = [
    "", "test no tag test", "test {unknown_tag} test", "{bin} {version}\\n{author}\\n{about}\\n\\nUSAGE:\\n    {usage}\\n\\n{all-args}",
    "{bin} {version}\\n{author}\\n{about}\\n\\nUSAGE:\\n    {usage}\\n\\nFLAGS:\\n{flags}\\nOPTIONS:\\n{options}\\nARGS:\\n{positionals}\\nSUBCOMMANDS:\\n{subcommands}\\n",
    "{unified}", "{before-help}|{after-help}|{long-about}", "{?}", "{}", "{", "x{", "{bin", "}{bin}{",
    "{this-tag-is-way-too-long} after", "{exactly14chars}", "{exactly14char}", "{{bin}}", "{ bin }", "{BIN}",
    "pre {flags", "ünï {about} 数字", "{version}{version}{author}{author}",
]
SIZES = {"S": (30, 2, 20), "M": (30, 300, 3000), "L": (30, 3000, 30000)}


def esc(s):
    return s


if __name__ == "__main__":
    out_dir = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180214 + i)
        n, lo, hi = SIZES[size]
        lines = []
        if size == "S":
            for app in range(3):
                lines += ["L\t%d\t%s" % (app, t) for t in LITERALS]
        lines += ["G\t%d\t%d\t%d" % (rng.randrange(3), rng.randint(lo, hi), rng.randrange(1, 2 ** 31)) for _ in range(n)]
        (out_dir / ("workload_%s.txt" % size)).write_text("\n".join(lines) + "\n", encoding="utf-8")
