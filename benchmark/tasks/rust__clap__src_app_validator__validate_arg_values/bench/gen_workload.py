"""Seeded workload generator for Validator::validate_arg_values (clap). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), one option argument + its matched values per line:
  <flags> <possible_values> <values>
flags: subset of C (CaseInsensitive), E (EmptyValues allowed), U (app has StrictUtf8), V (validator: rejects values
containing "bad"), O (validator_os: rejects values longer than 40 bytes), N (arg not recorded in the matcher), or "-".
possible_values: space-separated list or "-" (none).
values: "|"-separated literal values (an empty field = one empty value, or no value at all with flag N; "~" = the invalid-UTF-8 byte string b"a\\xffb"), or
"#<n>:<seed>:<bad>" = <n> values generated by the driver (xorshift, <seed>) from the possible values (random ASCII case
if C) or from words, followed by one offending value when <bad> = 1 (kind chosen by the driver from the flags).
"""
import random, sys
from pathlib import Path

LITERALS = [
    "-\t-\tone|two", "-\tfast slow\tfast", "-\tfast slow\tslow|fast|slow", "-\tfast slow\tfaster",
    "-\tfast slow\tFAST", "C\tfast slow\tFAST|Slow", "C\tfast slow\tfst", "-\ttest123 test321\ttest32",
    "-\t-\t", "-\t-\tok|", "E\t-\tok|", "N\t-\t", "-\tfast slow\t|fast", "E\tfast slow\t",
    "U\t-\t~", "-\t-\t~", "U\tfast\tfast|~", "V\t-\tgood|bad", "V\t-\tgood", "O\t-\tshort",
    "O\t-\tthis-value-is-definitely-longer-than-forty-bytes", "VO\tbad\tbad", "CEUVO\tAbc dEf\tabc|DEF|abc",
    "-\tcafé 数字\tcafé|数字", "C\tcafé\tCAFé", "C\tcafé\tCAFÉ",
]
SIZES = {"S": (40, 0, 8), "M": (40, 500, 5000), "L": (40, 5000, 50000)}


def case(rng, lo, hi):
    flags = "".join(f for f in "CEUVO" if rng.random() < 0.3) or "-"
    pv = "-" if rng.random() < 0.25 else " ".join("v%d%s" % (i, rng.choice(["", "x", "Long-Name"])) for i in range(rng.randint(1, 30)))
    bad = 1 if rng.random() < 0.3 else 0
    return "\t".join([flags, pv, "#%d:%d:%d" % (rng.randint(lo, hi), rng.randrange(1, 2 ** 31), bad)])


if __name__ == "__main__":
    out_dir = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180214 + i)
        n, lo, hi = SIZES[size]
        lines = list(LITERALS) if size == "S" else []
        lines += [case(rng, lo, hi) for _ in range(n)]
        (out_dir / ("workload_%s.txt" % size)).write_text("\n".join(lines) + "\n", encoding="utf-8")
