"""Seeded workload generator for expand_bytes (regex 1.0.0). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <reps> <pat> <hex template>     literal replacement template
  G <reps> <pat> <seed> <len>       template of ~<len> bytes generated by the driver (splitmix64) from literal text
                                    (incl. non-ASCII and invalid UTF-8), $N / ${N} / $name / ${name} references to existing and
                                    missing groups, $$ escapes, lone/invalid $ forms and over-long numbers.
<pat> indexes the driver's fixed (regex, text) table; the Captures of that regex on that text are computed before timing.
The output buffer starts as "PRE:" in check mode (the function must append).
<reps> = how many times the call is repeated in time mode.
"""
import random, sys
from pathlib import Path

BYTES = True
LITERALS = [
    (1, "$foo"), (1, "$0"), (1, "$1"), (1, "$$1"), (1, "$$foo"),
    (0, "$b$a"), (0, "z$bz$az"), (0, ".$b.$a."), (0, " $b $a "), (0, "$bz$az"),
    (6, "$2 $1"), (6, "$2 $$1"), (2, "$last $first$space"), (4, "$1-$2"), (7, "${1}a $1a"),
    (3, "$2 $1"), (3, "[$2|$1]"), (5, "${x_1}-${Y2}-${_z}-$3-$4"), (0, ""), (0, "$"), (0, "no refs at all"),
    (0, "$$"), (0, "${"), (0, "${}"), (0, "$ $"), (0, "日本$1"), (0, "$1日本"), (1, "${foo}bar$foobar"),
    (0, "${a"), (0, "$4294967296"), (0, "$007$00"), (1, "$$$$$foo$"), (1, "$é$fooé"),
]
if BYTES:
    LIT_B = [(p, t.encode()) for p, t in LITERALS] + [(0, b"\xff$a\xfe"), (1, b"$foo\x80$\xff")]
else:
    LIT_B = [(p, t.encode()) for p, t in LITERALS]

SIZES = {"S": (24, (10, 80), 200), "M": (24, (1500, 4000), 20), "L": (24, (15000, 40000), 8)}


def lines(size, rng):
    n, (lo, hi), reps = SIZES[size]
    out = []
    if size == "S":
        out += ["L\t%d\t%d\t%s" % (reps, p, t.hex()) for p, t in LIT_B]
    for _ in range(n):
        out.append("G\t%d\t%d\t%d\t%d" % (reps, rng.randrange(8), rng.randrange(1, 2**62), rng.randint(lo, hi)))
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180502 + 600 + i)
        (out / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
