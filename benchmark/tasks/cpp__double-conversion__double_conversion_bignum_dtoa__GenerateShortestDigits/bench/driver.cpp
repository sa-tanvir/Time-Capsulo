// Time Capsulo bench driver. argv: <size> <repeat> <mode>   (mode = check | time)
// Compiled with g++ -O2 -std=c++11 -DNDEBUG -I/w, together with the other library sources.
#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <string>
#include <vector>
#include <stdint.h>

namespace tcb
{
	struct Rng
	{
		uint64_t s;
		explicit Rng(uint64_t seed): s(seed) {}
		uint64_t next()
		{
			s += 0x9E3779B97F4A7C15ULL;
			uint64_t z = s;
			z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL;
			z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL;
			return z ^ (z >> 31);
		}
		uint64_t below(uint64_t n) { return n ? next() % n : 0; }
		int range(int lo, int hi) { return lo + static_cast<int>(below(static_cast<uint64_t>(hi - lo + 1))); }
	};

	struct Hash
	{
		uint64_t h;
		Hash(): h(1469598103934665603ULL) {}
		void add(const void* p, size_t n)
		{
			const unsigned char* c = static_cast<const unsigned char*>(p);
			for (size_t i = 0; i < n; ++i) { h ^= c[i]; h *= 1099511628211ULL; }
		}
		void u64(uint64_t v) { add(&v, 8); }
		void str(const char* s, size_t n) { u64(n); add(s, n); }
		std::string hex() const { char b[32]; snprintf(b, sizeof b, "%016llx", static_cast<unsigned long long>(h)); return b; }
	};

	inline std::vector<std::string> split_tabs(const std::string& line)
	{
		std::vector<std::string> out;
		size_t pos = 0;
		for (;;)
		{
			size_t t = line.find('\t', pos);
			if (t == std::string::npos) { out.push_back(line.substr(pos)); break; }
			out.push_back(line.substr(pos, t - pos));
			pos = t + 1;
		}
		return out;
	}

	inline std::vector<std::string> load_lines(const char* size)
	{
		const char* task = getenv("TC_TASK");
		std::string path = std::string(task ? task : "/task") + "/bench/workload_" + size + ".txt";
		std::ifstream in(path.c_str(), std::ios::binary);
		if (!in) { fprintf(stderr, "cannot open %s\n", path.c_str()); exit(2); }
		std::vector<std::string> lines;
		std::string line;
		while (std::getline(in, line)) if (!line.empty()) lines.push_back(line);
		return lines;
	}
}

#include "double-conversion/bignum-dtoa.cc"
using namespace double_conversion;

// Workload lines (tab separated): <reps> <seed> <n> <emin> <emax> <single(0|1)>
// n positive finite numbers are generated by the driver; the binary exponent of each is drawn from [emin, emax].
// The driver reproduces the set-up done by BignumDtoa (SHORTEST / SHORTEST_SINGLE) and then calls GenerateShortestDigits.
struct Item { uint64_t bits; bool single; };
struct Case { int reps; std::vector<Item> items; };
static std::vector<Case> g_cases;
static const int kMaxItems = 1000;
static Bignum *g_n, *g_d, *g_dm, *g_dp;
static char* g_buf;
static int* g_len;
static bool* g_even;

static void prepare(const std::vector<std::string>& lines)
{
	g_n = new Bignum[kMaxItems]; g_d = new Bignum[kMaxItems]; g_dm = new Bignum[kMaxItems]; g_dp = new Bignum[kMaxItems];
	g_buf = new char[kMaxItems * 32]; g_len = new int[kMaxItems]; g_even = new bool[kMaxItems];
	for (size_t i = 0; i < lines.size(); ++i)
	{
		std::vector<std::string> f = tcb::split_tabs(lines[i]);
		Case c;
		c.reps = atoi(f[0].c_str());
		tcb::Rng r(strtoull(f[1].c_str(), 0, 10));
		int n = atoi(f[2].c_str()), emin = atoi(f[3].c_str()), emax = atoi(f[4].c_str());
		bool single = atoi(f[5].c_str()) != 0;
		for (int k = 0; k < n; ++k)
		{
			Item it; it.single = single;
			int e = r.range(emin, emax);
			uint64_t mant;
			switch (r.below(6))
			{
			case 0: mant = 0; break;                                   // exact power of two (closer lower boundary)
			case 1: mant = r.below(1000); break;                        // small mantissa
			case 2: mant = (1ULL << 52) - 1 - r.below(4); break;        // all ones
			default: mant = r.next();
			}
			if (single)
			{
				if (e < -126) e = -126; if (e > 127) e = 127;
				float f32 = static_cast<float>(1.0f);
				uint32_t b = (static_cast<uint32_t>(e + 127) << 23) | static_cast<uint32_t>(mant & 0x7FFFFF);
				memcpy(&f32, &b, 4);
				double d = f32;
				memcpy(&it.bits, &d, 8);
			}
			else
			{
				if (e < -1022) e = -1022; if (e > 1023) e = 1023;
				it.bits = (static_cast<uint64_t>(e + 1023) << 52) | (mant & ((1ULL << 52) - 1));
			}
			c.items.push_back(it);
		}
		if (c.items.size() > static_cast<size_t>(kMaxItems)) { fprintf(stderr, "too many items\n"); exit(3); }
		g_cases.push_back(c);
	}
}

static size_t ncases() { return g_cases.size(); }
static int reps(size_t i) { return g_cases[i].reps; }

static void reset(size_t i)
{
	const Case& c = g_cases[i];
	for (size_t k = 0; k < c.items.size(); ++k)
	{
		double v; memcpy(&v, &c.items[k].bits, 8);
		uint64_t significand; int exponent; bool lower_closer;
		if (c.items[k].single)
		{
			float f = static_cast<float>(v);
			significand = Single(f).Significand(); exponent = Single(f).Exponent(); lower_closer = Single(f).LowerBoundaryIsCloser();
		}
		else
		{
			significand = Double(v).Significand(); exponent = Double(v).Exponent(); lower_closer = Double(v).LowerBoundaryIsCloser();
		}
		bool is_even = (significand & 1) == 0;
		g_even[k] = is_even;
		int ne = NormalizedExponent(significand, exponent);
		int est = EstimatePower(ne);
		InitialScaledStartValues(significand, exponent, lower_closer, est, true, &g_n[k], &g_d[k], &g_dm[k], &g_dp[k]);
		int dp;
		FixupMultiply10(est, is_even, &dp, &g_n[k], &g_d[k], &g_dm[k], &g_dp[k]);
	}
}

static uint64_t exec(size_t i)
{
	const Case& c = g_cases[i];
	uint64_t s = 0;
	for (size_t k = 0; k < c.items.size(); ++k)
	{
		GenerateShortestDigits(&g_n[k], &g_d[k], &g_dm[k], &g_dp[k], g_even[k], Vector<char>(g_buf + k * 32, 32), &g_len[k]);
		s += static_cast<uint64_t>(g_len[k]) + static_cast<unsigned char>(g_buf[k * 32]);
	}
	return s;
}

static void digest(size_t i, tcb::Hash& h)
{
	for (size_t k = 0; k < g_cases[i].items.size(); ++k) h.str(g_buf + k * 32, g_len[k]);
}

// hooks provided above: prepare(lines), ncases(), reps(i), reset(i) [untimed], exec(i) [timed, returns checksum], digest(i, h)
int main(int argc, char** argv)
{
	if (argc < 4) { fprintf(stderr, "usage: driver <size> <repeat> <mode>\n"); return 2; }
	const char* size = argv[1];
	int repeat = atoi(argv[2]);
	std::string mode = argv[3];

	prepare(tcb::load_lines(size));
	size_t n = ncases();

	if (mode == "check")
	{
		tcb::Hash h;
		for (size_t i = 0; i < n; ++i)
		{
			reset(i);
			exec(i);
			digest(i, h);
		}
		printf("{\"cases\": %zu, \"output_digest\": \"%s\"}\n", n, h.hex().c_str());
		return 0;
	}

	uint64_t sink = 0;
	double elapsed = 0;
	typedef std::chrono::steady_clock clk;
	for (int r = 0; r < repeat; ++r)
		for (size_t i = 0; i < n; ++i)
			for (int k = 0, kr = reps(i); k < kr; ++k)
			{
				reset(i);
				clk::time_point t0 = clk::now();
				sink += exec(i);
				clk::time_point t1 = clk::now();
				elapsed += std::chrono::duration<double>(t1 - t0).count();
			}
	fprintf(stderr, "checksum %llu\n", static_cast<unsigned long long>(sink));
	printf("{\"cases\": %zu, \"repeat\": %d, \"elapsed_s\": %.6f}\n", n, repeat, elapsed);
	return 0;
}
