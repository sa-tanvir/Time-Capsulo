"""Seeded workload generator for Help::spec_vals (clap). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs; "-" means "not set":
  <flags> <hide_pv> <env> <default> <aliases> <possible_values>
flags: subset of "E" (HideEnvValues), "D" (HideDefaultValue), "P" (HidePossibleValues), or "-".
hide_pv: 1/0, the Help writer's global "hide possible values" switch.
env: "NAME" (variable not set) or "NAME=VALUE". default: default value text.
aliases / possible_values: space-separated words (an alias prefixed with "!" is hidden), or "#<count>:<seed>"
= <count> words generated by the driver: word i = WORDS[(seed + 7*i) % len(WORDS)] + str(i % 10)
(aliases generated this way are all visible).
"""
import random, sys
from pathlib import Path

WORDS = ["fast", "slow", "vi", "emacs", "Nearest", "Linear", "Cubic", "Gaussian", "Lanczos3", "café", "数",
         "on", "off", "auto", "x", "always", "never", "ä-b", "json", "yaml"]
LITERALS = [
    "-\t0\t-\t-\t-\tfast slow",
    "-\t0\tENVVAR\t-\t-\t-",
    "-\t0\tENVVAR=MYVAL\t-\t-\t-",
    "E\t0\tENVVAR=MYVAL\t-\t-\tfast slow",
    "-\t0\t-\tdefault-argument\t-\t-",
    "D\t0\t-\tdefault-argument\t-\t-",
    "-\t0\t-\t-\tals\t-",
    "-\t0\t-\t-\t!invisible als2 als3\t-",
    "-\t0\t-\t-\t!invisible\t-",
    "P\t0\t-\t-\t-\tvi emacs",
    "-\t1\t-\t-\t-\tvi emacs",
    "-\t0\tE=V\tdflt\ta1 a2\tp1 p2 p3",
    "EDP\t1\tE=V\tdflt\ta1 a2\tp1 p2 p3",
    "-\t0\t-\t-\t-\t-",
    "-\t0\tEMPTY=\t-\t-\t-",
]
SIZES = {"S": (150, 0, 5), "M": (300, 300, 3000), "L": (400, 3000, 30000)}


def words(rng, n, alias):
    if n > 8:
        return "#%d:%d" % (n, rng.randrange(1000))
    if n == 0:
        return "-"
    return " ".join(("!" if alias and rng.random() < 0.2 else "") + rng.choice(WORDS) for _ in range(n))


def case(rng, lo, hi):
    flags = "".join(f for f in "EDP" if rng.random() < 0.2) or "-"
    hide = "1" if rng.random() < 0.15 else "0"
    env = rng.choice(["-", "-", "VAR%d" % rng.randrange(99), "VAR%d=%s" % (rng.randrange(99), rng.choice(WORDS))])
    dflt = rng.choice(["-", "-", rng.choice(WORDS), "some default %d" % rng.randrange(1000)])
    al = words(rng, rng.randint(lo, hi) if rng.random() < 0.6 else 0, True)
    pv = words(rng, rng.randint(lo, hi) if rng.random() < 0.8 else 0, False)
    return "\t".join([flags, hide, env, dflt, al, pv])


if __name__ == "__main__":
    out_dir = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180214 + i)
        n, lo, hi = SIZES[size]
        lines = list(LITERALS) if size == "S" else []
        lines += [case(rng, lo, hi) for _ in range(n)]
        (out_dir / ("workload_%s.txt" % size)).write_text("\n".join(lines) + "\n", encoding="utf-8")
