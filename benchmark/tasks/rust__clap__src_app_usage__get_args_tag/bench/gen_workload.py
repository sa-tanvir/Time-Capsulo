"""Seeded workload generator for usage::get_args_tag (clap). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), one App per line:
  L <dont_collapse> <spec>                literal positional list: <spec> = space-separated items
                                          name[:flags[:valnames]] where flags ⊆ R(required) H(hidden) L(last)
                                          M(multiple) G(member of required group) g(member of optional group),
                                          valnames = comma-separated value names
  G <dont_collapse> <n_pos> <pct> <seed>  <n_pos> positionals generated by the driver (xorshift, <seed>); each
                                          flag is set with probability ~<pct>%, value names (1-3) sometimes.
Positionals get indices 1..n in order. Each app is evaluated with incl_reqs = true and false.
"""
import random, sys
from pathlib import Path

LITERALS = [
    "0\t", "0\ta", "0\ta:R", "0\ta b", "1\ta b", "0\ta:R b", "0\ta:R b c", "1\ta:R b c", "0\ta b:R c",
    "0\ta b:H", "0\ta b:L", "0\ta:M", "0\ta:M:x", "0\ta:M:x,y", "0\ta::x,y", "0\ta:R b:M", "1\ta:R b:M c:H d:L",
    "0\ta:G b", "0\ta:G b:G", "0\ta:g b", "0\ta:G b c:R", "1\ta:G b:g c", "0\ta:R b c:R d", "0\ta:H b:H",
    "1\ta:H", "0\ta:L", "1\ta:L b:L", "0\ta:R b:L c:R", "0\tfirst:M:one,two,three",
]
SIZES = {"S": (30, 1, 8), "M": (30, 50, 500), "L": (30, 500, 5000)}


if __name__ == "__main__":
    out_dir = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180214 + i)
        n, lo, hi = SIZES[size]
        lines = ["L\t" + l for l in LITERALS] if size == "S" else []
        lines += ["G\t%d\t%d\t%d\t%d" % (rng.randrange(2), rng.randint(lo, hi), rng.choice([0, 3, 10, 30]),
                                         rng.randrange(1, 2 ** 31)) for _ in range(n)]
        (out_dir / ("workload_%s.txt" % size)).write_text("\n".join(lines) + "\n", encoding="utf-8")
