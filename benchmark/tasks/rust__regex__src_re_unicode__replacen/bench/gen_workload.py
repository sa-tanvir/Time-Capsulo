"""Seeded workload generator for Regex::replacen (re_unicode, regex 1.0.0). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <reps> <pat> <kind> <rep> <limit> <hex text>    literal text
  G <reps> <pat> <kind> <rep> <limit> <seed> <len>  text of ~<len> bytes generated by the driver (splitmix64):
      words, digits, spaces/tabs/newlines and non-ASCII characters
  <pat>   index into the driver's PATTERNS table; <kind> P (plain literal replacement), T (template with $ refs),
  N (NoExpand), F (closure, call count recorded); <rep> index into the driver's replacement table for <kind>;
  <limit> replacen limit (0 = all).
<reps> = how many times the call is repeated on that case in time mode.
"""
import random, sys
from pathlib import Path

BYTES = False
# (pat, kind, rep, limit, text) -- the cases of tests/replace.rs plus edge cases
LITERALS = [
    (0, "P", 0, 1, b"age: 26"), (10, "P", 0, 1, b"age: 26"), (0, "P", 0, 0, b"age: 26"),
    (11, "T", 0, 1, b"w1 w2"), (11, "T", 1, 1, b"w1 w2"), (1, "T", 2, 0, b"w1 w2 w3 w4"),
    (4, "P", 1, 0, b" \t  trim me\t   \t"), (12, "T", 3, 1, b"ab"), (6, "T", 4, 0, b"a b"),
    (13, "T", 5, 0, b"a b"), (13, "T", 6, 0, b"a b"), (11, "N", 0, 1, b"w1 w2"), (11, "N", 1, 1, b"w1 w2"),
    (7, "P", 1, 0, b"foobar"), (5, "P", 2, 1, b"bar"), (14, "T", 7, 0, b"b"),
    (3, "P", 3, 0, b"axxb"), (8, "P", 3, 0, b"abc"), (8, "P", 3, 2, b"abc"), (9, "P", 3, 0, b"ab cd"),
    (2, "P", 0, 0, b""), (15, "P", 0, 0, b"no match here"), (15, "T", 0, 0, b"no match here"),
    (15, "F", 0, 0, b"no match here"), (2, "F", 0, 3, b"banana boat"), (1, "F", 1, 0, b"one two three four five"),
    (2, "T", 8, 0, b"aeiou"), (0, "T", 9, 2, b"1 22 333 4444"), (2, "N", 2, 0, b"vowels"),
]
if BYTES:
    LITERALS += [(0, "P", 0, 0, b"\xff1\xfe22\x80"), (16, "T", 9, 0, b"a\xffb\xffc")]
else:
    LITERALS += [(2, "P", 0, 0, "héllo wörld 日本".encode()), (6, "T", 4, 0, "éè 日本".encode())]

NREP = {"P": 4, "T": 10, "N": 3, "F": 2}
PATS = [0, 1, 2, 3, 4, 5, 6, 7, 9, 11, 13, 15]
# size -> (n_cases, (min_len, max_len), reps)
SIZES = {"S": (40, (20, 200), 20), "M": (40, (2000, 6000), 5), "L": (40, (20000, 60000), 5)}


def lines(size, rng):
    n, (lo, hi), reps = SIZES[size]
    out = []
    if size == "S":
        out += ["L\t%d\t%d\t%s\t%d\t%d\t%s" % (reps, p, k, r, lim, t.hex()) for p, k, r, lim, t in LITERALS]
    for _ in range(n):
        k = rng.choice("PTTNF")
        out.append("G\t%d\t%d\t%s\t%d\t%d\t%d\t%d" % (reps, rng.choice(PATS), k, rng.randrange(NREP[k]),
                                                      rng.choice([0, 0, 0, 1, 2, 7, 50]),
                                                      rng.randrange(1, 2**62), rng.randint(lo, hi)))
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180502 + 200 + i)
        (out / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
