"""Seeded workload generator for BoyerMooreSearch::find (regex 1.0.0). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <reps> <hex pattern> <hex haystack>                         literal case
  G <reps> <seed> <hay_len> <alpha> <pat_len> <plant> <near>    case generated by the driver (splitmix64):
      alpha: 'text' (English-like letter/space distribution), 'dna' (ACGT), 'bin2' (bytes 0/1),
             'bin256' (uniform bytes), 'zeros' (mostly 0x00 with rare others);
      pattern = <pat_len> bytes drawn from the same distribution; haystack = <hay_len> bytes from it with
      <near> near-miss copies of the pattern (one byte altered) inserted, and the pattern itself planted
      at <plant> permille of the haystack length (-1 = not planted; it may still occur by chance).
<reps> = how many times the call is repeated on that case in time mode.
"""
import random, sys
from pathlib import Path

LITERALS = [
    (b"pattern", b"I keep seeing patterns in this text"),
    (b"pattern", b"I keep seeing needles in this text"),
    (bytes([0, 1, 1, 0]), bytes([0, 0, 0, 0, 0, 1, 1, 0])),
    (bytes([0, 0]), bytes([0, 0])),
    (bytes([91]), bytes([91])),
    (bytes([1, 1, 1, 1, 32, 32, 87]), bytes([0] * 27 + [87] + [0] * 70 + [1, 1, 1, 1, 32, 32, 87])),
    (b"clone_created", b"// " + b"a" * 32 + b"\ne_data.clone_created(entity_id, entity_to_add.entity_id);\n" + b"a" * 60 + b"\n" + b"a" * 32 + b"\n"),
    (bytes([1] * 7), bytes([0] * 86)),
    (b"abc", b"ab"), (b"abc", b"abc"), (b"abc", b"xabcabc"), (b"a", b"bbbbbbbba"), (b"a", b""),
    (b"aaaa", b"aaaaaaaaaa"), (b"abab", b"abaababab"), (b"zz", b"z" * 50), (b"\xff\x00", b"\x00\xff" * 30 + b"\xff\x00"),
    (b"needle", b"needl" * 40 + b"needle"), (b"eeeeeeeeeeee", b"e" * 11 + b"x" + b"e" * 12),
]
if False:
    LITERALS += [(b"", b""), (b"", b"abc")]

ALPHAS = ["text", "dna", "bin2", "bin256", "zeros"]
# size -> (n_cases, (min_hay, max_hay), reps)
SIZES = {"S": (30, (50, 400), 400), "M": (30, (4000, 12000), 100), "L": (30, (40000, 120000), 150)}


def lines(size, rng):
    n, (lo, hi), reps = SIZES[size]
    out = []
    if size == "S":
        out += ["L\t%d\t%s\t%s" % (reps, p.hex(), h.hex()) for p, h in LITERALS]
    for _ in range(n):
        alpha = rng.choice(ALPHAS)
        pat_len = rng.choice([1, 2, 3, 5, 8, 10, 13, 20, 32, 64])
        plant = rng.choice([-1, 0, 500, 900, 1000])
        near = rng.choice([0, 3, 30, 300])
        out.append("G\t%d\t%d\t%d\t%s\t%d\t%d\t%d" % (reps, rng.randrange(1, 2**62), rng.randint(lo, hi), alpha,
                                                     pat_len, plant, near))
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180502 + 0 + i)
        (out / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
