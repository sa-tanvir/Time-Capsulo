"""Seeded workload generator for InstRanges::matches (regex 1.0.0). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs:
  L <reps> <ranges> <queries>          literal case; ranges "a-b,c-d,..." and queries "x,y,..." as hex code points
                                       (query "none" = absent character, Char::from(None))
  G <reps> <seed> <n_ranges> <region> <n_queries>
      ranges generated by the driver (splitmix64): 2*n distinct scalar values from the region
      ('ascii' = U+0000-U+00FF, 'bmp' = U+0000-U+FFFF, 'all' = all scalar values), sorted and paired
      into sorted, non-overlapping inclusive ranges; queries mix range bounds +/-1, random values in the
      region, random ASCII and absent characters.
<reps> = how many times all queries of the case are repeated in time mode.
"""
import random, sys
from pathlib import Path

LITERALS = [
    ([("61", "7a")], ["0", "60", "61", "6d", "7a", "7b", "10ffff", "none"]),
    ([("0", "2"), ("4", "6")], ["0", "2", "3", "4", "6", "7", "ff"]),
    ([("30", "39"), ("41", "5a"), ("5f", "5f"), ("61", "7a")], ["2f", "30", "39", "3a", "40", "41", "5a", "5b", "5f", "60", "61", "7a", "7b", "e9"]),
    ([("30", "39"), ("41", "5a"), ("5f", "5f"), ("61", "7a"), ("aa", "aa"), ("b5", "b5"), ("ba", "ba"), ("c0", "d6"), ("d8", "f6")],
     ["aa", "ab", "b5", "ba", "bb", "c0", "d6", "d7", "d8", "f6", "f7", "61", "29"]),
    ([("0", "10ffff")], ["0", "d7ff", "e000", "10ffff", "none"]),
    ([("0", "9"), ("b", "10ffff")], ["9", "a", "b", "none"]),
    ([("2028", "2029")], ["2027", "2028", "2029", "202a", "a"]),
    ([("10000", "10ffff")], ["ffff", "10000", "1f600"]),
    ([("41", "41")], ["41", "40", "42"]),
]

SIZES = {"S": (12, (1, 8), 300, 400), "M": (12, (60, 200), 300, 100), "L": (12, (1500, 4000), 300, 1000)}


def lines(size, rng):
    n, (lo, hi), nq, reps = SIZES[size]
    out = []
    if size == "S":
        for rs, qs in LITERALS:
            out.append("L\t%d\t%s\t%s" % (reps * 10, ",".join("%s-%s" % r for r in rs), ",".join(qs)))
    for _ in range(n):
        region = rng.choice(["ascii", "bmp", "all"]) if size == "S" else rng.choice(["bmp", "all", "all"])
        out.append("G\t%d\t%d\t%d\t%s\t%d" % (reps, rng.randrange(1, 2**62), rng.randint(lo, hi), region, nq))
    return out


if __name__ == "__main__":
    out = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180502 + 700 + i)
        (out / ("workload_%s.txt" % size)).write_text("\n".join(lines(size, rng)) + "\n", encoding="utf-8")
