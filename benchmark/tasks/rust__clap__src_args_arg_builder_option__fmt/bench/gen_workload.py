"""Seeded workload generator for OptBuilder's Display impl (clap). Usage: python3 gen_workload.py <out_dir>

Line format (tab-separated), parsed by driver.rs; "-" means "not set":
  <name> <long> <short> <flags> <delim> <num_vals> <val_names>
flags: subset of "M" (Multiple), "E" (RequireEquals), "D" (RequireDelimiter); "-" for none.
delim: value delimiter char (only meaningful with D). val_names: space-separated value names, "-" = None, or "#<count>:<seed>" = <count> names generated by
the driver: name i = WORDS[(seed + 7*i) % len(WORDS)] (same WORDS list as below).
"""
import random, sys
from pathlib import Path

WORDS = ["file", "name", "val", "path", "out", "in", "x", "level", "mode", "key", "port", "host", "user",
         "FILE", "PATH", "N", "count", "dir", "spec", "pattern", "ärger", "数", "id", "url"]
LITERALS = [
    "opt\toption\t-\tM\t-\t-\t-",
    "opt\t-\to\t-\t-\t-\tfile name",
    "opt\t-\to\tM\t-\t-\tfile name",
    "opt\toption\t-\t-\t-\t-\t-",
    "fake\tfake\tf\tD\t:\t2\tsome val",
    "o\topt\to\tE\t-\t-\tFILE",
    "o\topt\to\tEM\t-\t-\tFILE",
    "o\t-\to\tE\t-\t-\t-",
    "o\topt\t-\tM\t-\t1\t-",
    "o\topt\t-\tM\t-\t3\t-",
    "o\topt\t-\tDM\t,\t3\t-",
    "o\topt\t-\t-\t-\t0\t-",
    "o\t-\tö\tM\t-\t-\tval",
    "o\tlong-name\tl\tDEM\t;\t-\ta",
    "o\tlong-name\tl\tDEM\t;\t-\ta b c",
    "num\tnum\t-\tM\t-\t2\t-",
]
SIZES = {"S": (120, 0, 6), "M": (300, 30, 1200), "L": (400, 3000, 12000)}  # (cases, min_vals, max_vals)


def case(rng, lo, hi):
    name = rng.choice(WORDS) + str(rng.randrange(100))
    long_ = rng.choice(["-", name, "long-" + name, "o"])
    short = rng.choice("abcdefXYZéß") if long_ == "-" or rng.random() < 0.5 else "-"
    flags = "".join(f for f in "MED" if rng.random() < 0.4) or "-"
    delim = rng.choice(",:;|/") if "D" in flags else "-"
    kind = rng.randrange(3)
    n = rng.randint(lo, hi)
    num_vals, names = "-", "-"
    if kind == 0:
        num_vals = str(n)
    elif kind == 1 and n > 0:
        names = " ".join(rng.choice(WORDS) for _ in range(n)) if n <= 8 else "#%d:%d" % (n, rng.randrange(1000))
    if delim == "-" and "D" in flags:
        delim = ","
    return "\t".join([name, long_, short, flags, delim, num_vals, names])


if __name__ == "__main__":
    out_dir = Path(sys.argv[1])
    for i, size in enumerate(["S", "M", "L"]):
        rng = random.Random(20180214 + i)
        n, lo, hi = SIZES[size]
        lines = list(LITERALS) if size == "S" else []
        lines += [case(rng, lo, hi) for _ in range(n)]
        (out_dir / ("workload_%s.txt" % size)).write_text("\n".join(lines) + "\n", encoding="utf-8")
